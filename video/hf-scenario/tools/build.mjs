//
// Usage (from video/hf-scenario):  node tools/build.mjs
// Reads:  data/storyboard.json   the shot list (presentations/2026-11_第二次簡報/01_情境劇劇本.md on a time line)
//         data/lines.json        length of every AI voice clip (tools/tts.py)
//         data/mixkit_lengths.json  music and sound effects from Mixkit (tools/mixkit.py)
//         data/sfx_lengths.json  the synthesised phone buzz (tools/sfx.py)
//         raw/                   the team's footage and voice-overs, when they exist ($FNV_SCENARIO_RAW overrides)
//         %TEMP%\fnv-scenario-raw  the live-site takes (tools/capture.mjs; $FNV_RAW overrides)
// Writes: compositions/*.html, index.html, data/schedule.json, renders/scenario.srt, and the baked media in
//         assets/footage/ and assets/audio/{live,rec}/.
//
// What stands in for what (since 2026-10-30 nobody is filmed: the owner narrates, the characters are AI voices):
//   - talk shot (the narrator explaining): a headline, the key points as chips, and a "旁白" badge whose bars move
//     while the narrator speaks. The sketches live inside the phone scenes: "char" adds the character's face and
//     mood beside the phone, "counter" and "pause" work on any shot, kind=call is a phone call screen.
//   - rec line (the narrator's voice-over, one phone recording per part, raw/V1.m4a …; the script to read is
//     generated by tools/rec_sheet.mjs): the recording is cut at the pauses between sentences and each sentence
//     goes to its line in order. Missing → AI voice and a "預覽版" watermark.
//   - live shot (kept for real footage, unused now): raw/<clip> → the clip and its own sound; the captions
//     follow the pauses in the speech. Missing → a placeholder card and AI voices.
//   - site step: one piece of a live-site take, with the last frame held until the voice-over ends; "zoom" adds
//     a still close-up of one part of the page (the verdict, the sources) beside the phone while it is talked about.
//   - threads step: raw/T1.mp4 cut by the step's segments once they are set; until then a labelled mock-up.
// Sound follows video-shotcraft's sound-design notes: one music bed under the whole film (restarting at the
// chapter cards, ducked under every spoken line), real-sounding effects instead of synthesised tones.
// Every composition is generated: edit the storyboard, not compositions/ or index.html.
