def _placeholders(table: str) -> str:
    spec = TABLE_SPECS[table]
    return ", ".join(
        f"CAST(:{c} AS {spec['casts'][c]})" if c in spec["casts"] else f":{c}" for c in spec["columns"]
    )


def insert_statement(table: str):
    columns = TABLE_SPECS[table]["columns"]
    return text(f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({_placeholders(table)})")


def upsert_statement(table: str, update_existing: bool = True):
    """
    以主鍵 id upsert。update_existing=True：只有內容不同的既有列才更新
    （ROW(...) IS DISTINCT FROM ROW(EXCLUDED...)），所以重跑一次不會動到任何列。
    """
    columns = TABLE_SPECS[table]["columns"]
    sql = f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({_placeholders(table)}) ON CONFLICT (id) "
    if not update_existing:
        return text(sql + "DO NOTHING")
    data_columns = [c for c in columns if c != "id"]
    assignments = ", ".join(f"{c} = EXCLUDED.{c}" for c in data_columns)
    current = ", ".join(f"{table}.{c}" for c in data_columns)
    incoming = ", ".join(f"EXCLUDED.{c}" for c in data_columns)
    return text(
        sql + f"DO UPDATE SET {assignments} WHERE ROW({current}) IS DISTINCT FROM ROW({incoming})"
    )


# ── 共用：延後取得 engine ─────────────────────────────────────────────────
class _PgStoreBase:
    def __init__(self, engine: Optional[Engine] = None) -> None:
        self._engine = engine
        self._autocommit_engine: Optional[Engine] = None
        self._init_lock = threading.Lock()

    def _connect(self) -> Connection:
        """AUTOCOMMIT 連線；第一次呼叫才取 engine 並確保資料表存在（失敗時下次重試）。"""
        if self._autocommit_engine is None:
            with self._init_lock:
                if self._autocommit_engine is None:
                    engine = self._engine
                    if engine is None:
                        from app.database_sql import get_pg_engine
                        engine = get_pg_engine()
                    if engine.dialect.name != "postgresql":
                        raise RuntimeError("Postgres store needs a postgresql engine")
                    ensure_pg_schema(engine)
                    self._engine = engine
                    self._autocommit_engine = engine.execution_options(isolation_level="AUTOCOMMIT")
        return self._autocommit_engine.connect()


# ── 知識庫（三層快取）─────────────────────────────────────────────────────
def _like_literal(value: str) -> str:
    """ILIKE 字面比對：跳脫 \\ % _（搭配 ESCAPE '\\'），使用者輸入的 % 不會變成萬用字元。"""
    return value.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


def _kb_frame(rows: List[Dict[str, Any]], include_vectors: bool = False) -> pd.DataFrame:
    """查詢結果 → 與本機版同形狀的 DataFrame（sources list、ai_analysis dict、時間 datetime64）。"""
    if not rows:
        return pd.DataFrame(columns=KB_COLUMNS)
    df = pd.DataFrame(rows, columns=KB_COLUMNS)
    df["sources"] = df["sources"].map(lambda v: v if isinstance(v, list) else [])
    if include_vectors:
        df["content_vector"] = df["content_vector"].map(
            lambda v: np.asarray(json.loads(v), dtype=np.float32) if isinstance(v, str) else None
        )
    for col in ("created_at", "last_accessed_at"):
        df[col] = pd.to_datetime(df[col], errors="coerce")
    df["is_risk"] = df["is_risk"].fillna(False).astype(bool)
    df["verified"] = df["verified"].fillna(False).astype(bool)
    df["hit_count"] = pd.to_numeric(df["hit_count"], errors="coerce").fillna(0).astype("int64")
    df["confidence_score"] = pd.to_numeric(df["confidence_score"], errors="coerce")
    df["source_tier"] = pd.to_numeric(df["source_tier"], errors="coerce")
    return df


def _kb_row(mapping: Any) -> Dict[str, Any]:
    row = dict(mapping)
    row.pop("similarity", None)
    if row.get("sources") is None:
        row["sources"] = []
    row.setdefault("content_vector", None)   # find_* 不載入向量（沒有呼叫端使用）
    return {col: row.get(col) for col in KB_COLUMNS}


class PgKnowledgeStore(_PgStoreBase):
    """PandasStore 的 Postgres 版（knowledge_base 表）。"""

    def _touch_first(self, column: str, value: str) -> Optional[Dict[str, Any]]:
        # column 只會是下面兩個常數之一；命中即 hit_count + 1（單一陳述式、一趟往返）
        statement = text(
            f"UPDATE knowledge_base SET hit_count = hit_count + 1, last_accessed_at = :now "
            f"WHERE id = (SELECT id FROM knowledge_base WHERE {column} = :value ORDER BY seq LIMIT 1) "
            f"RETURNING {_KB_READ_SQL}"
        )
        with self._connect() as conn:
            row = conn.execute(statement, {"now": datetime.now(), "value": value}).mappings().first()
        return _kb_row(row) if row is not None else None

    # Layer 0
    def find_by_url(self, url: str) -> Optional[Dict[str, Any]]:
        """以來源 URL 查找快取（同網址多筆取最早寫入者），命中時更新 hit_count。"""
        if _is_missing(url):
            return None
        return self._touch_first("source_url", str(url))

    # Layer 1
    def find_by_hash(self, content_hash: str) -> Optional[Dict[str, Any]]:
        """根據 SHA-256 Hash 查找快取（同 hash 多筆取最早寫入者）。"""
        if _is_missing(content_hash):
            return None
        return self._touch_first("data_hash", str(content_hash))

    # Layer 2
    def find_similar_by_vector(
        self,
        query_vector: List[float],
        threshold: Optional[float] = None,
        label_sources: Optional[Iterable[str]] = None,
    ) -> Optional[Dict[str, Any]]:
        """
        cosine similarity 最高且 >= threshold 的「verified」列（FR-17）；threshold 預設
        settings.SIMILARITY_THRESHOLD。空向量／零向量／維度不符 → None（不查資料庫）。
        label_sources：只比對這些 label_source 的列（None = 不限），與本機版相同。
        """
        if threshold is None:
            from app.config import settings
            threshold = settings.SIMILARITY_THRESHOLD
        if query_vector is None or len(query_vector) == 0:
            return None
        literal = vector_literal(query_vector)
        if literal is None or not np.any(np.asarray(query_vector, dtype=np.float32)):
            return None

        label_filter = "" if label_sources is None else "  AND label_source = ANY(:labels)"
        returning = ", ".join(f"kb.{c}" for c in _KB_READ_COLUMNS)
        statement = text(
            "WITH best AS ("
            "  SELECT id, 1 - (content_vector <=> CAST(:q AS vector)) AS similarity"
            "  FROM knowledge_base"
            "  WHERE verified AND content_vector IS NOT NULL"
            f"{label_filter}"
            "  ORDER BY content_vector <=> CAST(:q AS vector), seq"
            "  LIMIT 1"
            ") "
            "UPDATE knowledge_base AS kb"
            " SET hit_count = kb.hit_count + 1, last_accessed_at = :now"
            " FROM best"
            # 零向量列的 cosine distance 是 NaN；Postgres 視 NaN 大於任何數，要另外擋掉
            " WHERE kb.id = best.id AND best.similarity >= :threshold"
            "   AND best.similarity <> CAST('NaN' AS double precision)"
            f" RETURNING {returning}, best.similarity"
        )
        params = {"q": literal, "now": datetime.now(), "threshold": float(threshold)}
        if label_sources is not None:
            params["labels"] = [str(label) for label in label_sources]
        with self._connect() as conn:
            row = conn.execute(statement, params).mappings().first()
        return _kb_row(row) if row is not None else None

    def nearest_verified(
        self,
        query_vector: List[float],
        k: int = 5,
        label_sources: Optional[Iterable[str]] = None,
    ) -> List[Dict[str, Any]]:
        """最接近的 k 筆已證實列（證據信心用；不設門檻、不更新 hit_count），與本機版相同。"""
        if query_vector is None or len(query_vector) == 0 or int(k) <= 0:
            return []
        literal = vector_literal(query_vector)
        if literal is None or not np.any(np.asarray(query_vector, dtype=np.float32)):
            return []
        label_filter = "" if label_sources is None else " AND label_source = ANY(:labels)"
        statement = text(
            f"SELECT {', '.join(NEIGHBOR_COLUMNS)}, 1 - (content_vector <=> CAST(:q AS vector)) AS similarity"
            " FROM knowledge_base WHERE verified AND content_vector IS NOT NULL"
            f"{label_filter}"
            " ORDER BY content_vector <=> CAST(:q AS vector), seq LIMIT :k"
        )
        params: Dict[str, Any] = {"q": literal, "k": int(k)}
        if label_sources is not None:
            params["labels"] = [str(label) for label in label_sources]
        with self._connect() as conn:
            rows = conn.execute(statement, params).mappings().all()
        neighbours = []
        for row in rows:
            similarity = row["similarity"]
            if similarity is None or math.isnan(float(similarity)):   # 零向量列的 cosine distance 是 NaN
                continue
            item = {col: row[col] for col in NEIGHBOR_COLUMNS}
            item["sources"] = item["sources"] or []
            item["similarity"] = float(similarity)
            neighbours.append(item)
        return neighbours

    def save_record(
        self,
        data_type: str,
        raw_content: str,
        content_hash: str,
        content_vector: Optional[List[float]] = None,
        ai_result: Optional[Dict[str, Any]] = None,
        source_url: Optional[str] = None,
        label_source: str = "ai",
        verified: Optional[bool] = None,
        origin: str = "web",
        last_result_id: Optional[str] = None,
        related_discussions: Any = None,
    ) -> Dict[str, Any]:
        record = build_kb_record(
            data_type=data_type, raw_content=raw_content, content_hash=content_hash,
            content_vector=content_vector, ai_result=ai_result, source_url=source_url,
            label_source=label_source, verified=verified, origin=origin,
            last_result_id=last_result_id, related_discussions=related_discussions,
        )
        params = self._row_params(record)
        with self._connect() as conn:
            conn.execute(insert_statement("knowledge_base"), params)
        if params["content_vector"] is None:
            record["content_vector"] = None   # 維度不是 1536：實際存的是 NULL
        return record

    def save_records(self, items: Iterable[Dict[str, Any]], batch_size: int = 200) -> int:
        """批次寫入（scripts/ingest_factchecks.py 用）：與 save_record 同一套內容，每批一次 executemany。"""
        params = [self._row_params(build_kb_record(**item)) for item in items]
        with self._connect() as conn:
            for start in range(0, len(params), batch_size):
                conn.execute(insert_statement("knowledge_base"), params[start:start + batch_size])
        return len(params)

    @staticmethod
    def _row_params(record: Dict[str, Any]) -> Dict[str, Any]:
        rd = record.get("related_discussions")
        if rd is not None and not isinstance(rd, str):
            record["related_discussions"] = json.dumps(_jsonable(rd), ensure_ascii=False)
        return kb_row_params(record)

    def get_all_records(self, include_vectors: bool = False) -> pd.DataFrame:
        """
        整張知識庫（依寫入順序），欄位與本機版相同：sources 是 list[dict]、ai_analysis 是 dict、
        related_discussions 是 JSON 字串、時間是 datetime64。content_vector 預設全為 None
        （每筆約 19 KB，API 與管理端都用不到）；include_vectors=True 才載入（np.ndarray）。
        """
        vector_sql = "CAST(content_vector AS text) AS content_vector" if include_vectors \
            else "NULL AS content_vector"
        statement = text(f"SELECT {_KB_READ_SQL}, {vector_sql} FROM knowledge_base ORDER BY seq")
        with self._connect() as conn:
            rows = [dict(r) for r in conn.execute(statement).mappings().all()]
        return _kb_frame(rows, include_vectors)

    # 知識庫頁查詢（/api/knowledge）：在資料庫裡篩選、計數與分頁，不把整張表載進記憶體
    # （2026-09 批次寫入查核機構資料後約 1.9 萬列；Render 免費主機只有 512 MB）。行為與本機版相同。
    def verified_counts(self) -> Tuple[Dict[str, int], int]:
        statement = text(
            "SELECT verified, COALESCE(NULLIF(risk_type, ''), 'UNKNOWN') AS risk, count(*) AS n"
            " FROM knowledge_base GROUP BY 1, 2"
        )
        by_risk: Dict[str, int] = {}
        unverified = 0
        with self._connect() as conn:
            for row in conn.execute(statement).mappings():
                if row["verified"]:
                    by_risk[row["risk"]] = by_risk.get(row["risk"], 0) + int(row["n"])
                else:
                    unverified += int(row["n"])
        return by_risk, unverified

    def list_verified(
        self, q: str = "", risk_type: str = "", limit: int = 30, offset: int = 0,
    ) -> Tuple[int, pd.DataFrame]:
        where, params = ["verified"], {}
        if q.strip():
            where.append("(raw_content ILIKE :q ESCAPE '\\' OR summary ILIKE :q ESCAPE '\\')")
            params["q"] = f"%{_like_literal(q.strip())}%"
        if risk_type.strip():
            where.append("upper(risk_type) = :risk")
            params["risk"] = risk_type.strip().upper()
        clause = " AND ".join(where)
        page_sql = text(
            f"SELECT {_KB_READ_SQL}, NULL AS content_vector FROM knowledge_base WHERE {clause}"
            " ORDER BY created_at DESC NULLS LAST, id ASC LIMIT :limit OFFSET :offset"
        )
        with self._connect() as conn:
            total = conn.execute(text(f"SELECT count(*) FROM knowledge_base WHERE {clause}"), params).scalar()
            rows = [dict(r) for r in conn.execute(
                page_sql, {**params, "limit": int(limit), "offset": int(offset)}).mappings().all()]
        return int(total or 0), _kb_frame(rows)

    def get_verified_by_ids(self, ids: Iterable[str]) -> pd.DataFrame:
        wanted = sorted({str(i) for i in ids if i})
        if not wanted:
            return pd.DataFrame(columns=KB_COLUMNS)
        statement = text(
            f"SELECT {_KB_READ_SQL}, NULL AS content_vector FROM knowledge_base"
            " WHERE verified AND id = ANY(:ids) ORDER BY seq"
        )
        with self._connect() as conn:
            rows = [dict(r) for r in conn.execute(statement, {"ids": wanted}).mappings().all()]
        return _kb_frame(rows)

    def apply_admin_override(self, kb_id: str, verdict: Dict[str, Any]) -> bool:
        """
        管理者覆寫（app/api/admin.py）：label_source=admin、verified=True，並把覆寫後的判定寫進
        頂層欄位與 ai_analysis（其餘鍵保留）。本機版是整檔重寫，這裡是單列 UPDATE。找不到列 → False。
        """
        converters = {
            "risk_type": _clean_text, "category": _clean_text,
            "confidence_score": _as_float, "is_risk": _as_bool,
        }
        fields = {k: convert(verdict[k]) for k, convert in converters.items() if k in verdict}
        assignments = ["label_source = 'admin'", "verified = TRUE"]
        assignments += [f"{k} = :{k}" for k in fields]
        assignments.append(
            "ai_analysis = CASE WHEN jsonb_typeof(ai_analysis) = 'object' "
            "THEN ai_analysis || CAST(:patch AS jsonb) ELSE ai_analysis END"
        )
        statement = text(f"UPDATE knowledge_base SET {', '.join(assignments)} WHERE id = :kb_id")
        patch = {k: verdict[k] for k in converters if k in verdict}
        params = {**fields, "patch": json.dumps(_jsonable(patch), ensure_ascii=False), "kb_id": str(kb_id)}
        with self._connect() as conn:
            return (conn.execute(statement, params).rowcount or 0) > 0


# ── 任務（結果頁 /r/{id} 的資料來源）──────────────────────────────────────
_TASK_SELECT_SQL = ", ".join(TASK_COLUMNS)


class PgTaskStore(_PgStoreBase):
    """TaskStore 的 Postgres 版（tasks 表）。"""

    def create_task(
        self,
        task_type: str,
        input_data: str,
        input_type: Optional[str] = None,
        origin: str = "web",
        **extra: Any,
    ) -> str:
        """建立 pending 任務；extra 只收 spec §6.1 新欄位，未知鍵忽略。超過上限時修剪（規則同本機版）。"""
        task_id = str(uuid.uuid4())
        now = datetime.utcnow()
        record: Dict[str, Any] = {
            "id": task_id,
            "task_type": task_type,
            "input_data": input_data,
            "status": "pending",
            "result_data": None,
            "error_message": None,
            "created_at": now,
            "updated_at": now,
            "completed_at": None,
        }
        record.update(_ts._NEW_COLUMN_DEFAULTS)
        record["input_type"] = input_type or _ts.input_type_from_task_type(task_type)
        record["origin"] = origin or "web"
        for key, value in extra.items():
            if key in _ts._NEW_COLUMN_DEFAULTS and key not in ("input_type", "origin"):
                record[key] = value

        # 只刪已結束（completed／failed）中最舊者；pending／processing 不砍（可暫時超過上限）
        prune = text(
            "DELETE FROM tasks WHERE id IN ("
            "  SELECT id FROM tasks WHERE status = ANY(:statuses) ORDER BY seq"
            "  LIMIT GREATEST((SELECT count(*) FROM tasks) - :cap, 0)"
            ")"
        )
        with self._connect() as conn:
            conn.execute(insert_statement("tasks"), task_row_params(record))
            conn.execute(prune, {"statuses": list(_ts._PRUNABLE_STATUSES), "cap": int(_ts._MAX_TASKS)})
        return task_id

    def update_task(self, task_id: str, **fields: Any) -> None:
        """更新任務欄位（未知欄位忽略；任務不存在時不做事）；updated_at 一律更新。"""
        values: Dict[str, Any] = {"updated_at": datetime.utcnow()}
        for key, value in fields.items():
            if key in TASK_COLUMNS:
                values[key] = task_value(key, value)
        assignments = ", ".join(f"{key} = :{key}" for key in values)
        statement = text(f"UPDATE tasks SET {assignments} WHERE id = :_task_id")
        with self._connect() as conn:
            conn.execute(statement, {**values, "_task_id": str(task_id)})

    def get_task(self, task_id: str) -> Optional[Dict[str, Any]]:
        """單一任務（時間轉 ISO 字串、布林／整數為 Python 型別；找不到 → None）。"""
        statement = text(f"SELECT {_TASK_SELECT_SQL} FROM tasks WHERE id = :task_id")
        with self._connect() as conn:
            row = conn.execute(statement, {"task_id": str(task_id)}).mappings().first()
        if row is None:
            return None
        record = dict(row)
        for key in _ts._DATETIME_COLUMNS:
            if isinstance(record.get(key), datetime):
                record[key] = record[key].isoformat()
        for key in _TASK_BOOL_COLUMNS:
            record[key] = bool(record.get(key)) if record.get(key) is not None else False
        if not record.get("input_type"):
            record["input_type"] = _ts.input_type_from_task_type(record.get("task_type"))
        return record

    def recent_kb_refs(self, since: datetime) -> List[Dict[str, Any]]:
        """since 之後建立、已完成、對應到知識庫列的任務 {kb_id, created_at, origin}（同本機版）。"""
        statement = text(
            "SELECT kb_id, created_at, origin FROM tasks"
            " WHERE status = 'completed' AND kb_id IS NOT NULL AND kb_id <> ''"
            "   AND created_at >= :since"
            " ORDER BY seq"
        )
        with self._connect() as conn:
            rows = conn.execute(statement, {"since": since}).mappings().all()
        return [
            {"kb_id": str(r["kb_id"]), "created_at": r["created_at"], "origin": r["origin"] or "web"}
            for r in rows
        ]


