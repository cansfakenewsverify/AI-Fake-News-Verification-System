class PgAuditStore(_PgStoreBase):
    """AuditStore 的 Postgres 版（admin_overrides／user_feedback 表）。"""

    def _append(self, table: str, columns: List[str], record: Dict[str, Any]) -> Dict[str, Any]:
        with self._connect() as conn:
            conn.execute(insert_statement(table), audit_row_params(record, columns))
        record["created_at"] = record["created_at"].isoformat()
        return record

    def _load(self, table: str, columns: List[str]) -> pd.DataFrame:
        statement = text(f"SELECT {', '.join(columns)} FROM {table} ORDER BY seq")
        with self._connect() as conn:
            rows = [dict(r) for r in conn.execute(statement).mappings().all()]
        return pd.DataFrame(rows, columns=columns)

    def _load_overrides(self) -> pd.DataFrame:
        return self._load("admin_overrides", OVERRIDE_COLUMNS)

    def _load_feedback(self) -> pd.DataFrame:
        return self._load("user_feedback", FEEDBACK_COLUMNS)

    def append_override(
        self,
        task_id: str,
        admin_id: str,
        reason: str,
        new_risk_type: Optional[str] = None,
        new_category: Optional[str] = None,
        new_confidence_score: Optional[float] = None,
    ) -> Dict[str, Any]:
        return self._append("admin_overrides", OVERRIDE_COLUMNS, {
            "id": str(uuid.uuid4()),
            "task_id": task_id,
            "new_risk_type": new_risk_type,
            "new_category": new_category,
            "new_confidence_score": new_confidence_score,
            "admin_id": admin_id,
            "reason": reason,
            "created_at": datetime.utcnow(),
        })

    def append_feedback(
        self,
        task_id: str,
        rating: str,
        comment: Optional[str] = None,
        user_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        return self._append("user_feedback", FEEDBACK_COLUMNS, {
            "id": str(uuid.uuid4()),
            "task_id": task_id,
            "user_id": user_id,
            "rating": rating,
            "comment": comment,
            "created_at": datetime.utcnow(),
        })
