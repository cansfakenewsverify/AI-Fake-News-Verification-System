def ensure_pg_schema(engine: Engine, force: bool = False) -> None:
    """
    pgvector 擴充 + 五張資料表（knowledge_base／tasks／admin_overrides／user_feedback／
    fact_check_records），全部 idempotent。同一個 engine 每個行程只跑一次（force=True 例外）。

    - Supabase 慣例：擴充裝在 extensions schema（連線的 search_path 已含 extensions，見 database_sql）。
    - fact_check_records 沿用既有 SQLAlchemy model；是否已存在只看「目前 schema」，不用 create_all 的
      可見性檢查（search_path 後段的 public 若已有同名表，會被誤判為已存在而不建）。
    - 啟用 RLS 且不建任何 policy：Supabase 會把 public schema 的表經 Data API 開放給 anon 金鑰，
      後端以資料表擁有者身分連線，不受 RLS 影響。
    """
    with _ENSURE_LOCK:
        if not force and engine in _ENSURED:
            return
        from app.models.fact_check_record import FactCheckRecord

        with engine.begin() as conn:
            has_extensions_schema = conn.exec_driver_sql(
                "SELECT 1 FROM pg_namespace WHERE nspname = 'extensions'"
            ).first() is not None
            conn.exec_driver_sql(
                "CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA "
                + ("extensions" if has_extensions_schema else "public")
            )
            for statement in _DDL_STATEMENTS:
                conn.exec_driver_sql(statement)
            has_fact_check = conn.exec_driver_sql(
                "SELECT to_regclass(quote_ident(current_schema()) || '.fact_check_records') IS NOT NULL"
            ).scalar()
            if not has_fact_check:
                FactCheckRecord.__table__.create(bind=conn, checkfirst=False)
            without_rls = conn.exec_driver_sql(
                "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
                "WHERE n.nspname = current_schema() AND c.relkind = 'r' "
                "AND NOT c.relrowsecurity AND c.relname = ANY(%s)",
                (list(ALL_TABLES),),
            ).scalars().all()
            for table in without_rls:
                if table in ALL_TABLES:
                    conn.exec_driver_sql(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        _ENSURED.add(engine)


# ── 值的正規化（numpy／pandas → Python 原生型別；Postgres 不收 NUL 與 NaN）──────────
def _is_missing(value: Any) -> bool:
    if value is None or value is pd.NaT:
        return True
    if isinstance(value, (list, tuple, dict, set, np.ndarray)):
        return False
    try:
        return bool(pd.isna(value))
    except (TypeError, ValueError):
        return False


def _clean_text(value: Any) -> Optional[str]:
    if _is_missing(value):
        return None
    return str(value).replace("\x00", "")


def _as_float(value: Any) -> Optional[float]:
    if _is_missing(value):
        return None
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def _as_int(value: Any) -> Optional[int]:
    number = _as_float(value)
    return int(number) if number is not None else None


def _as_bool(value: Any, default: bool = False) -> bool:
    return default if _is_missing(value) else bool(value)


def _as_datetime(value: Any) -> Optional[datetime]:
    """naive datetime（時區資訊一律先轉 UTC 再去掉）；無法解析 → None。"""
    if _is_missing(value):
        return None
    if isinstance(value, np.datetime64):
        value = pd.Timestamp(value)
    if isinstance(value, pd.Timestamp):
        value = value.to_pydatetime(warn=False)
    if isinstance(value, str):
        try:
            value = datetime.fromisoformat(value.strip())
        except ValueError:
            return None
    if not isinstance(value, datetime):
        return None
    if value.tzinfo is not None:
        value = value.astimezone(timezone.utc).replace(tzinfo=None)
    return value


def _jsonable(value: Any) -> Any:
    """遞迴轉成可存 jsonb 的純 Python 物件（ndarray → list、NaN → null、字串去 NUL）。"""
    if isinstance(value, dict):
        return {str(k).replace("\x00", ""): _jsonable(v) for k, v in value.items()}
    if isinstance(value, np.ndarray):
        return [_jsonable(v) for v in value.tolist()]
    if isinstance(value, (list, tuple, set)):
        return [_jsonable(v) for v in value]
    if isinstance(value, np.generic):
        return _jsonable(value.item())
    if _is_missing(value):
        return None
    if isinstance(value, bool):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, int):
        return value
    if isinstance(value, datetime):
        return value.isoformat()
    return str(value).replace("\x00", "")


def _to_json(value: Any) -> Optional[str]:
    if _is_missing(value):
        return None
    return json.dumps(_jsonable(value), ensure_ascii=False)


def _drop_none_keys(sources: Any) -> List[Any]:
    """Parquet 的 struct 會替每筆來源補上其他列才有的鍵（值為 None）；jsonb 不需要這些佔位。"""
    cleaned = []
    for item in _jsonable(sources) or []:
        cleaned.append({k: v for k, v in item.items() if v is not None} if isinstance(item, dict) else item)
    return cleaned


def vector_literal(vector: Any) -> Optional[str]:
    """pgvector 文字格式；None／空／維度不是 1536／含 NaN、inf → None（存 NULL、不參與比對）。"""
    if vector is None:
        return None
    try:
        with np.errstate(over="ignore", invalid="ignore"):
            arr = np.asarray(vector, dtype=np.float32)   # pgvector 以 float4 儲存；本機版也用 float32 比對
    except (TypeError, ValueError):
        return None
    if arr.ndim != 1 or arr.shape[0] != VECTOR_DIM or not np.isfinite(arr).all():
        return None
    return "[" + ",".join(format(x, ".9g") for x in arr.tolist()) + "]"


